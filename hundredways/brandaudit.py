"""Brand-coverage audit for present and *future* upstream files.

The token map in :mod:`hundredways.rules` is validated against the fork's birth
commit and is therefore frozen: a future transform change would grow the
birth-parity drift set.  That leaves two blind spots no map-bound check can see:

* **Discovery** - a brand-new upstream file (or a plain upstream edit) can carry
  a brand *spelling* the map does not know (``HERMESCLOUD``, ``hermescloud``, a
  fresh camel run-on).  No rule fires, so the file ships unbranded and no existing
  gate notices.  :func:`discover_brand_tokens` scans a source tree for
  brand-family occurrences the canonical rules leave untouched and reports them
  as candidate tokens for a human token-map decision.
* **Residue** - a candidate file that still contains a token some rule *would*
  rewrite.  :func:`residual_brand_lines` reports every such line with evidence.

:func:`plan_issues` turns either finding (plus the credential scan) into a
reviewable GitHub-issue draft, and :func:`create_issues` only ever creates them
when explicitly asked.  Creating an issue is a human decision, exactly like
merging a review PR, so the default is a dry run that touches nothing.

This module never edits the token map.  Proposing a spelling is safe; adopting it
is a reviewed change to ``config/rules_override.json`` or a documented reconcile
with a regression test.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import string
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from .brandassets import AssetIssue, audit_brand_assets
