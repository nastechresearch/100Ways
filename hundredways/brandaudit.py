from .rules import BrandingRules, is_immutable_path, is_locked_path
from .secrets import EXTENDED_SECRET_PATTERNS, redact

# ---------------------------------------------------------------------------
# Discovery: find brand spellings the frozen token map cannot reach.
# ---------------------------------------------------------------------------

# A stem only counts when it is not glued to a preceding *letter of its own
# casing class*, mirroring the rules.  Discovery is case-precise on purpose: the
# camelCase "ou" in ``noUsageData`` is not the lowercase ``nous`` token, and
# ordinary English words ("venous", "synchronous") must never be reported.
_STEM_RE = re.compile(
    r"(?<![a-z])(?P<lower>hermes|nous)"
    r"|(?<![A-Z])(?P<title>Hermes|Nous)"
    r"|(?<![A-Z])(?P<upper>HERMES|NOUS)"
)
_RUN_CHARS = frozenset(string.ascii_letters + string.digits)
_SKIP_DIRS = frozenset({".git", "node_modules"})
_MAX_SCAN_BYTES = 2 * 1024 * 1024

_REVIEW_FOOTER = "Generated by 100Ways \u00b7 review only \u2014 never merge, tag, or release."


def _run_at(text: str, start: int, end: int) -> str:
    """Expand ``[start, end)`` to the surrounding identifier run."""
    while start > 0 and text[start - 1] in _RUN_CHARS:
        start -= 1
    while end < len(text) and text[end] in _RUN_CHARS:
        end += 1
    return text[start:end]


def _iter_text_files(root: str):
    """Yield ``(path, relative)`` for every scannable text file under ``root``."""
    base = Path(root)
    for path in sorted(base.rglob("*")):
        if not path.is_file():
            continue
        if any(part in _SKIP_DIRS for part in path.parts):
            continue
        relative = path.relative_to(base).as_posix()
        if is_immutable_path(relative) or is_locked_path(relative):
            continue
        try:
            if path.stat().st_size > _MAX_SCAN_BYTES:
                continue
        except OSError:
            continue
        yield path, relative


@dataclass(frozen=True)
class BrandTokenCandidate:
    """A brand-family spelling present in the source tree that no rule rewrites."""

    token: str
    count: int
    samples: tuple[str, ...] = ()

    def to_dict(self) -> dict[str, object]:
        return {"token": self.token, "count": self.count, "samples": list(self.samples)}


def discover_brand_tokens(
    root: str,
    rules: BrandingRules | None = None,
    max_samples: int = 8,
) -> list[BrandTokenCandidate]:
    """Return brand spellings in ``root`` that the canonical rules leave untouched.

    Covered spellings (``hermes``, ``NousResearch``, ``HermesCloud``) are dropped;
    only spellings that would ship *unbranded* survive, sorted by frequency.
    """
    rules = rules or BrandingRules()
    counts: dict[str, int] = {}
    samples: dict[str, list[str]] = {}
    for path, relative in _iter_text_files(root):
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        lowered = text.lower()
        if "hermes" not in lowered and "nous" not in lowered:
            continue
        for line_number, line in enumerate(text.splitlines(), start=1):
            for match in _STEM_RE.finditer(line):
                run = _run_at(line, match.start(), match.end())
                if not run or rules.transform_text(run) != run:
                    continue  # covered by an existing rule
                counts[run] = counts.get(run, 0) + 1
                bucket = samples.setdefault(run, [])
                if len(bucket) < max_samples:
                    bucket.append(f"{relative}:{line_number}")
    ordered = sorted(counts.items(), key=lambda item: (-item[1], item[0]))
    return [
        BrandTokenCandidate(token, count, tuple(samples.get(token, ())))
        for token, count in ordered
    ]


# ---------------------------------------------------------------------------
# Residue: a candidate file a rule would still rewrite.
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class BrandResidual:
    """One candidate line that still contains a token an active rule rewrites."""

    path: str
    line: int
    snippet: str
    tokens: tuple[str, ...] = ()

    def to_dict(self) -> dict[str, object]:
        return {
            "path": self.path,
            "line": self.line,
            "snippet": self.snippet,
            "tokens": list(self.tokens),
        }


def _matching_tokens(line: str, rules: BrandingRules) -> tuple[str, ...]:
    return tuple(token.match for token in rules.tokens if token.match in line)


def residual_brand_lines(
    root: str,
    rules: BrandingRules | None = None,
    max_lines: int = 500,
) -> list[BrandResidual]:
    """Return candidate lines that the canonical rules would still rewrite.

    A whole file that is already a transform fixed point costs one comparison
    and is skipped; only a surviving file is scanned line by line for evidence.
    """
    rules = rules or BrandingRules()
    found: list[BrandResidual] = []
    for path, relative in _iter_text_files(root):
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        if rules.transform_text(text) == text:
            continue
        for number, line in enumerate(text.splitlines(), start=1):
            if rules.transform_text(line) == line:
                continue
            found.append(
                BrandResidual(relative, number, line.strip()[:200], _matching_tokens(line, rules))
            )
            if len(found) >= max_lines:
                return found
    return found


