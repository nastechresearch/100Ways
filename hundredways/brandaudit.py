@dataclass(frozen=True)
class SecretFinding:
    """One credential-shaped value found in the audited tree."""

    path: str
    line: int
    pattern: str
    snippet: str

    def to_dict(self) -> dict[str, object]:
        return {
            "path": self.path,
            "line": self.line,
            "pattern": self.pattern,
            "snippet": self.snippet,
        }


def scan_credentials(root: str, max_findings: int = 500) -> list[SecretFinding]:
    """Scan ``root`` for credential-shaped values, returning redacted evidence."""
    findings: list[SecretFinding] = []
    for path, relative in _iter_text_files(root):
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        for number, line in enumerate(text.splitlines(), start=1):
            hits = [pattern.pattern for pattern in EXTENDED_SECRET_PATTERNS if pattern.search(line)]
            if not hits:
                continue
            findings.append(
                SecretFinding(relative, number, ", ".join(hits), redact(line.strip())[:200])
            )
            if len(findings) >= max_findings:
                return findings
    return findings


