MARKER = re.compile(r"100ways:issue:([a-z0-9][a-z0-9-]*)")
FOOTER = (
    "Generated by 100Ways \u00b7 proposal only \u2014 nothing was created unless an "
    "operator ran this with --apply."
)

CI = "ci"
URLS = "urls"
SURFACE = "surface"
CREDENTIALS = "credentials"
ORPHANS = "orphans"
FEED = "feed"

SUGGESTIONS = "suggestions"
ISSUES = "issues"
DISCUSSIONS = "discussions"
TABLE_KINDS: tuple[str, ...] = (SUGGESTIONS, ISSUES, DISCUSSIONS)

_UNNAMED = "(unnamed run)"

# The next action for a credential verdict.  Keyed on pubconfig's own verdict
# constants, so a verdict the gate does not produce cannot get an action here.
_CREDENTIAL_ACTIONS = {
    LIVE_MISSING: "configure the name, or gate the lane that reads it",
    UNGATED_CONSUMED: "add the name to the lane's gate set, or configure it",
    "partial-gate": "finish the gate: a half-set is already a silent skip",
    "declared-skip": "nothing: the fork publishes without this lane by design",
    "configured": "nothing: every reader of this name has it",
}

_MEANINGS = {
    ("cli-verb", "removed"): "a command the fork ships disappears upstream",
    ("cli-verb", "changed"): "upstream renamed a verb the fork already brands around",
    ("env-var", "removed"): "a credential name the fork gates is gone",
    ("signature", "changed"): "callers must be rewritten or the port will not import",
    ("entry-point", "removed"): "a published plugin name disappears",
}


class DeliveryError(RuntimeError):
    """The live state could not be read, so no deduplication may be claimed."""


@dataclass(frozen=True)
class Suggestion:
    """One next action, with who owes it -- the line a chat answer is built from."""

    key: str
    kind: str
    text: str
    owner: str

    def __post_init__(self) -> None:
        # A key is built from whatever the measurement named -- a credential name, a
        # path -- so it is masked here rather than at each printer: ``plan_json`` writes
        # these dicts straight to an artifact, and an artifact is the one place a value
        # must never arrive.
        for field in ("key", "kind", "text", "owner"):
            object.__setattr__(self, field, redact(getattr(self, field)))

    def to_dict(self) -> dict[str, object]:
        return {"key": self.key, "kind": self.kind, "text": self.text, "owner": self.owner}


@dataclass(frozen=True)
class DiscussionDraft:
    """A question for the repository's Discussions board.

    The REST create endpoint for a discussion takes a title, a body and a category and
    nothing else -- no labels -- so no labels field pretends to work here.
    """

    key: str
    title: str
    body: str
    category: str = ""

    def __post_init__(self) -> None:
        for field in ("key", "title", "body", "category"):
            object.__setattr__(self, field, redact(getattr(self, field)))

    def to_dict(self) -> dict[str, object]:
        return {
            "key": self.key,
            "title": self.title,
            "body": self.body,
            "category": self.category or "(repo default)",
        }


@dataclass(frozen=True)
class Plan:
    """What would be written, what was measured to work it out, and what was not."""

    issues: tuple[IssueDraft, ...] = ()
    discussions: tuple[DiscussionDraft, ...] = ()
    suggestions: tuple[Suggestion, ...] = ()
    measured: tuple[str, ...] = ()
    skipped: tuple[str, ...] = ()

    @property
    def actionable(self) -> int:
        return len(self.issues) + len(self.discussions)

    def to_dict(self) -> dict[str, object]:
        return {
            "measured": list(self.measured),
            "skipped": list(self.skipped),
            "actionable": self.actionable,
            "issues": [draft.to_dict() for draft in self.issues],
            "discussions": [draft.to_dict() for draft in self.discussions],
            "suggestions": [item.to_dict() for item in self.suggestions],
        }


def _cell(value: object) -> str:
    """Make a value safe for a markdown table cell, and safe to publish."""
    return redact(str(value)).replace("|", "\\|").replace("\n", " ")


def _slug(value: object) -> str:
    """A key that :data:`MARKER` can read back whole.

    The marker regex accepts lower-case letters, digits and hyphens only, so a key built
    from an engine constant that contains an underscore -- ``BRAND_VIOLATION``,
    ``RUNNER_CAPACITY`` -- would be found as a *prefix* of itself and deduplicate the
    wrong draft.  Every key therefore passes through here.
    """
    return re.sub(r"[^a-z0-9-]", "-", str(value).lower())


def _issue(key: str, title: str, lines: Iterable[str], labels: Sequence[str],
           blocking: bool) -> IssueDraft:
    body = "\n".join([*lines, "", f"<!-- 100ways:issue:{key} -->", FOOTER])
    return IssueDraft(
        key=key,
        title=redact(title),
        body=body,
        labels=tuple(labels),
        severity="blocking" if blocking else "warning",
    )


def _discussion(key: str, title: str, lines: Iterable[str], category: str = "") -> DiscussionDraft:
    body = "\n".join([*lines, "", f"<!-- 100ways:issue:{key} -->", FOOTER])
    return DiscussionDraft(key=key, title=redact(title), body=body, category=category)


def _rows(header: Sequence[str], cells: Sequence[Sequence[str]]) -> list[str]:
    """A markdown table, because a list of twelve lanes is unreadable."""
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    lines += ["| " + " | ".join(_cell(value) for value in row) + " |" for row in cells]
    return lines


def _ci(verdicts: Sequence[Verdict]) -> tuple[list[IssueDraft], list[DiscussionDraft],
                                              list[Suggestion]]:
    """One issue per class, addressed to the owner that class already names."""
    buckets: dict[str, list[Verdict]] = {}
    for verdict in verdicts:
        buckets.setdefault(verdict.kind.value, []).append(verdict)
    drafts: list[IssueDraft] = []
    tips: list[Suggestion] = []
    for kind in sorted(buckets):
        members = sorted(buckets[kind], key=lambda item: item.check)
        owner = members[0].owner
        drafts.append(
            _issue(
                _slug(f"ci-{kind}"),
                f"CI: {len(members)} {kind} red(s) -- owner: {owner}",
                [
                    f"These lanes were classified {kind} from the check-runs payload that was"
                    f" read. The engine's own owner table assigns them to: **{owner}**.",
                    "",
                    *_rows(("lane", "next action"),
                           [(v.check or _UNNAMED, v.action) for v in members]),
                    "",
                    "Evidence per lane, as measured:",
                    *(f"- {_cell(v.check or _UNNAMED)}: {'; '.join(v.evidence)}"
                      for v in members),
                ],
                ("ci-red", _slug(kind)),
                blocking=False,
            )
        )
        tips += [
            Suggestion(
                key=f"ci.{kind}.{v.check or _UNNAMED}",
                kind=CI,
                text=v.action,
                owner=v.owner,
            )
            for v in members
        ]
    return drafts, [], tips


def _urls(findings: Sequence[UrlFinding]) -> tuple[list[IssueDraft], list[DiscussionDraft],
                                                   list[Suggestion]]:
    """Only a judged link is a finding: an unanswered probe belongs to neither group."""
    judged = [item for item in findings if item.status in DECIDED]
    buckets: dict[str, list[UrlFinding]] = {}
    for item in judged:
        buckets.setdefault(item.status, []).append(item)
    drafts: list[IssueDraft] = []
    tips: list[Suggestion] = []
    for status in sorted(buckets):
        members = sorted(buckets[status], key=lambda item: (item.link.path, item.link.line))
        drafts.append(
            _issue(
                _slug(f"urls-{status}"),
                f"Links: {len(members)} {status.replace('_', '-').lower()} link(s) to fix",
                [
                    "Every link below was read from the shipped tree and judged by the"
                    " engine's URL policy. A link nobody probed is not in this list: an"
                    " answer that never left the process is not evidence.",
                    "",
                    *_rows(
                        ("path", "line", "url", "what to do"),
                        [
                            (m.link.path, str(m.link.line), m.link.url,
                             m.suggestion or m.detail)
                            for m in members
                        ],
                    ),
                ],
                ("links", _slug(status)),
                blocking=True,
            )
        )
        tips += [
            Suggestion(
                key=f"urls.{m.link.path}.{m.link.line}",
                kind=URLS,
                text=m.suggestion
                or f"remove or replace the link at {m.link.path}:{m.link.line}",
                owner="whoever owns that file",
            )
            for m in members
        ]
    return drafts, [], tips


def _surface(deltas: Sequence[SurfaceDelta]) -> tuple[list[IssueDraft], list[DiscussionDraft],
                                                      list[Suggestion]]:
    """A movement the fork must handle is an issue; one it may choose to take is a question."""
    needing = sorted((d for d in deltas if d.classification == RULE),
                     key=lambda d: (d.field, d.kind, d.before, d.after))
    choosing = sorted((d for d in deltas if d.classification in (ADOPT, BRAND)),
                      key=lambda d: (d.field, d.kind, d.before, d.after))
    drafts: list[IssueDraft] = []
    talks: list[DiscussionDraft] = []
    tips: list[Suggestion] = []
    if needing:
        drafts.append(
            _issue(
                "surface-rule-needed",
                f"Surface: {len(needing)} upstream movement(s) the transform cannot absorb",
                [
                    "These are on the surface upstream exposes. A removal or a widened"
                    " signature is not adopted on the fork's own behalf: the branded tree"
                    " has to change with it, or the next sync breaks.",
                    "",
                    *_rows(
                        ("movement", "what it means"),
                        [
                            (f"{d.field} {d.kind}: {d.value}",
                             _MEANINGS.get((d.field, d.kind),
                                          "a fork-side change is required"))
                            for d in needing
                        ],
                    ),
                ],
                ("surface", "needs-review"),
                blocking=False,
            )
        )
        tips += [
            Suggestion(
                key=f"surface.{d.field}.{d.value}",
                kind=SURFACE,
                text=f"decide the fork-side change for {d.field} {d.kind}: {d.value}",
                owner="100Ways transform",
            )
            for d in needing
        ]
    if choosing:
        talks.append(
            _discussion(
                "surface-adopt-or-refuse",
                f"Surface: {len(choosing)} upstream name(s) the fork has not decided on",
                [
                    "Each movement below is something upstream added. Nothing breaks if the"
                    " fork ignores it, so the engine will not choose for you: adopting a new"
                    " verb, entry point or credential name is a product decision.",
                    "",
                    *_rows(
                        ("movement", "classification"),
                        [(f"{d.field} {d.kind}: {d.value}", d.classification)
                         for d in choosing],
                    ),
                    "",
                    "Movements already marked ignored are not listed: those are recorded"
                    " decisions, not open questions.",
                ],
            )
        )
        tips += [
            Suggestion(
                key=f"surface.{d.field}.{d.value}",
                kind=SURFACE,
                text=f"adopt or refuse the new {d.field} {d.value}",
                owner="whoever owns the fork's surface",
            )
            for d in choosing
        ]
    return drafts, talks, tips


def _credentials(findings: Sequence[Finding]) -> tuple[list[IssueDraft], list[DiscussionDraft],
                                                      list[Suggestion]]:
    holes = sorted((item for item in findings if item.actionable),
                   key=lambda item: (item.verdict, item.name))
    if not holes:
        return [], [], []
    draft = _issue(
        "credentials-unreadable",
        f"Credentials: {len(holes)} name(s) a live run would read as an empty string",
        [
            "Each name below is consumed by a job that can run in this repository and is"
            " not provided by the Actions settings that were read. No value is shown here:"
            " a name is the only thing needed to fix it, and it is the only thing recorded.",
            "",
            *_rows(
                ("name", "verdict", "scope", "next action"),
                [
                    (item.name, item.verdict, ", ".join(item.scopes) or "-",
                     _CREDENTIAL_ACTIONS.get(item.verdict, "decide what closes this"))
                    for item in holes
                ],
            ),
        ],
        ("credentials", "needs-review"),
        blocking=True,
    )
    tips = [
        Suggestion(
            key=f"credentials.{item.name}",
            kind=CREDENTIALS,
            text=_CREDENTIAL_ACTIONS.get(item.verdict, "decide what closes this"),
            owner="the repo owner",
        )
        for item in holes
    ]
    return [draft], [], tips


def _orphans(orphans: Sequence[Orphan]) -> tuple[list[IssueDraft], list[DiscussionDraft],
                                                 list[Suggestion]]:
    """A file whose upstream twin is gone is a defect; an unexplained file is a question."""
    lost = sorted((o for o in orphans if o.kind == "deleted-twin"), key=lambda o: o.path)
    odd = sorted((o for o in orphans if o.kind != "deleted-twin"), key=lambda o: o.path)
    drafts: list[IssueDraft] = []
    talks: list[DiscussionDraft] = []
    tips: list[Suggestion] = []
    if lost:
        drafts.append(
            _issue(
                "orphans-deleted-twin",
                f"Orphans: {len(lost)} fork file(s) whose upstream twin no longer exists",
                [
                    "These paths exist only in the fork because the upstream file they were"
                    " branded from is gone. Nothing deletes them: a fork-only file is"
                    " allowed, an unexplained one is how a stale transform survives.",
                    "",
                    *_rows(("path", "evidence", "what to do"),
                           [(o.path, o.evidence, o.suggestion) for o in lost]),
                ],
                ("orphans", "needs-review"),
                blocking=True,
            )
        )
        tips += [
            Suggestion(
                key=f"orphans.{o.path}",
                kind=ORPHANS,
                text=o.suggestion or f"explain or remove {o.path}",
                owner="whoever added that file",
            )
            for o in lost
        ]
    if odd:
        talks.append(
            _discussion(
                "orphans-unexplained",
                f"Orphans: {len(odd)} fork file(s) with no upstream twin at all",
                [
                    "No upstream file brands into these paths, so the sync will never touch"
                    " them. That is right if they are deliberately Nastech-only, and drift if"
                    " they are not. The engine cannot tell which, so it is asking.",
                    "",
                    *_rows(("path", "what was looked for"),
                           [(o.path, o.evidence) for o in odd]),
                ],
            )
        )
        tips += [
            Suggestion(
                key=f"orphans.{o.path}",
                kind=ORPHANS,
                text=f"confirm {o.path} is meant to be fork-only, or remove it",
                owner="whoever owns that directory",
            )
            for o in odd
        ]
    return drafts, talks, tips


def _feed(feed: Feed, *, name_owners: bool) -> tuple[list[IssueDraft], list[DiscussionDraft],
                                                     list[Suggestion]]:
    """What only a comparison between cycles can show: holes in the observation itself.

    ``name_owners`` is false when the verdicts were handed over as well, because the CI
    family already opens one issue per class -- including UNKNOWN -- and a lane must not
    be asked for twice.
    """
    unproved = sorted((e for e in feed.events if e.kind == UNPROVED), key=lambda e: e.lane)
    unowned = sorted(feed.unowned)
    drafts: list[IssueDraft] = []
    tips: list[Suggestion] = []
    if unproved:
        drafts.append(
            _issue(
                "feed-unproved-clearances",
                f"Error feed: {len(unproved)} lane(s) a partial read cannot account for",
                [
                    "These lanes were red in the previous cycle and are not in the payload"
                    " that was just read -- but that payload did not list every check run,"
                    " so their absence is not evidence that they went green.",
                    "",
                    f"- why: {feed.partial_reason}",
                    *(f"- `{_cell(e.lane)}` was {e.cls}" for e in unproved),
                ],
                ("ci-red", "needs-review"),
                blocking=False,
            )
        )
        tips.append(
            Suggestion(
                key="feed.read-completeness",
                kind=FEED,
                text="read every page of the check runs before claiming a lane cleared",
                owner="whoever runs the triage",
            )
        )
    if unowned and name_owners:
        drafts.append(
            _issue(
                "feed-lanes-without-owner",
                f"Error feed: {len(unowned)} red lane(s) the classifier could not place",
                [
                    "UNKNOWN is not a low-severity verdict: it means nothing in the payload"
                    " said who owns the fix, so the lane stays red until a person reads it.",
                    "",
                    *_rows(("lane",), [(lane,) for lane in unowned]),
                ],
                ("ci-red", "needs-review"),
                blocking=False,
            )
        )
        tips += [
            Suggestion(
                key=f"feed.{lane}",
                kind=FEED,
                text=f"read the log for {lane} and name the owner",
                owner=str(OWNERS[RedClass.UNKNOWN]),
            )
            for lane in unowned
        ]
    return drafts, [], tips


def plan(
    *,
    verdicts: Sequence[Verdict] | None = None,
    urls: Sequence[UrlFinding] | None = None,
    deltas: Sequence[SurfaceDelta] | None = None,
    credentials: Sequence[Finding] | None = None,
    orphans: Sequence[Orphan] | None = None,
    feed: Feed | None = None,
) -> Plan:
    """Draft issues and discussions from the measurements that were actually handed over.

    ``None`` means the family was not measured, which is recorded in
    :attr:`Plan.skipped`; an empty sequence means it was measured and found nothing, and
    correctly drafts nothing.  A family that was not measured never contributes a
    suggestion, so the answer a commander gets cannot read as a clean repository.
    """
    given = {
        CI: verdicts,
        URLS: urls,
        SURFACE: deltas,
        CREDENTIALS: credentials,
        ORPHANS: orphans,
        FEED: feed,
    }
    issues: list[IssueDraft] = []
    talks: list[DiscussionDraft] = []
    tips: list[Suggestion] = []
    if verdicts is not None:
        writes, questions, actions = _ci(verdicts)
        issues += writes
        talks += questions
        tips += actions
    if urls is not None:
        writes, questions, actions = _urls(urls)
        issues += writes
        talks += questions
        tips += actions
    if deltas is not None:
        writes, questions, actions = _surface(deltas)
        issues += writes
        talks += questions
        tips += actions
    if credentials is not None:
        writes, questions, actions = _credentials(credentials)
        issues += writes
        talks += questions
        tips += actions
    if orphans is not None:
        writes, questions, actions = _orphans(orphans)
        issues += writes
        talks += questions
        tips += actions
    if feed is not None:
        writes, questions, actions = _feed(feed, name_owners=verdicts is None)
        issues += writes
        talks += questions
        tips += actions
    return Plan(
        issues=tuple(sorted(issues, key=lambda draft: draft.key)),
        discussions=tuple(sorted(talks, key=lambda draft: draft.key)),
        suggestions=tuple(sorted(tips, key=lambda tip: (tip.kind, tip.key))),
        measured=tuple(name for name, value in given.items() if value is not None),
        skipped=tuple(name for name, value in given.items() if value is None),
    )


def render_plan(result: Plan) -> str:
    """One markdown document: what would be written, and what was not measured."""
    lines = [
        "# 100Ways delivery plan",
        "",
        f"- issues: {len(result.issues)}",
        f"- discussions: {len(result.discussions)}",
        f"- suggestions: {len(result.suggestions)}",
        f"- measured: {', '.join(result.measured) or 'nothing'}",
    ]
    if result.skipped:
        lines.append(f"- not measured: {', '.join(result.skipped)}")
    lines.append("")
    for draft in result.issues:
        lines += [
            f"## issue [{draft.severity}] {draft.title}",
            f"- labels: {', '.join(draft.labels) or '-'}",
            "",
            draft.body,
            "",
        ]
    for draft in result.discussions:
        lines += [
            f"## discussion {draft.title}",
            f"- category: {draft.category or '(repo default)'}",
            "",
            draft.body,
            "",
        ]
    if not result.issues and not result.discussions:
        lines += ["_nothing to write: no drafted issue or discussion._", ""]
    lines.append(FOOTER)
    return "\n".join(redact(line) for line in lines) + "\n"


def render_suggestions(result: Plan, *, limit: int = 0) -> str:
    """The plain-text answer a chat sends: numbered next actions, nothing invented."""
    if not result.suggestions:
        head = "Suggestions: none, from the families that were measured."
        if result.skipped:
            head += f" Not measured: {', '.join(result.skipped)}."
        return redact(head) + "\n"
    shown = result.suggestions[:limit] if limit else result.suggestions
    lines = [f"Suggestions: {len(result.suggestions)} next action(s)"]
    lines += [
        f"{i}. [{tip.kind}] {tip.text} -- {tip.owner}" for i, tip in enumerate(shown, start=1)
    ]
    if len(shown) < len(result.suggestions):
        lines.append(
            f"_showing {len(shown)} of {len(result.suggestions)}: "
            f"{len(result.suggestions) - len(shown)} withheld by --limit_"
        )
    if result.skipped:
        lines.append(f"not measured, so nothing to suggest there: {', '.join(result.skipped)}")
    return "\n".join(redact(line) for line in lines) + "\n"


def plan_json(result: Plan) -> dict[str, object]:
    """The machine form, for a workflow artifact or the console."""
    return result.to_dict()


def plan_table(result: Plan, kind: str = SUGGESTIONS) -> Table:
    """A plan laid out as a chat table: the same rows, never more than one page asks for.

    The families are the plan's own objects, so a table cannot disagree with the markdown
    document it came from -- and a kind that names nothing prints ``0 row(s)``, which is
    only ever true of a family that was measured.
    """
    if kind == SUGGESTIONS:
        return build(
            "100WAYS / NEXT ACTIONS",
            ("kind", "action", "owner"),
            [(tip.kind, tip.text, tip.owner) for tip in result.suggestions],
            notes=(f"{len(result.suggestions)} action(s)", _families(result)),
        )
    if kind == ISSUES:
        return build(
            "100WAYS / ISSUES TO OPEN",
            ("key", "severity", "title"),
            [(draft.key, draft.severity, draft.title) for draft in result.issues],
            notes=(f"{len(result.issues)} draft(s)", _families(result)),
        )
    if kind == DISCUSSIONS:
        return build(
            "100WAYS / QUESTIONS TO ASK",
            ("key", "title", "category"),
            [(draft.key, draft.title, draft.category or "(repo default)")
             for draft in result.discussions],
            notes=(f"{len(result.discussions)} draft(s)", _families(result)),
        )
    raise TableError(f"no delivery family called {kind!r}: use one of {TABLE_KINDS}")


def _families(result: Plan) -> str:
    if not result.skipped:
        return f"measured: {', '.join(result.measured) or 'nothing'}"
    return f"measured: {', '.join(result.measured) or 'nothing'}; not: {', '.join(result.skipped)}"


def _gh_read(repo: str, path: str, *flags: str, run: Callable[..., Any] = subprocess.run) -> str:
    """One read-only ``gh api`` call, with a failure that is not allowed to look empty."""
    if shutil.which("gh") is None:
        raise DeliveryError("gh is not on PATH: the open list cannot be read")
    try:
        result = run(
            ["gh", "api", "--paginate", f"repos/{repo}/{path}", *flags],
            capture_output=True,
            text=True,
        )
    except OSError as exc:
        raise DeliveryError(f"gh could not be run: {redact(str(exc))}")
    if getattr(result, "returncode", 1) != 0:
        detail = (getattr(result, "stderr", "") or getattr(result, "stdout", "")).strip()
        tail = detail.splitlines()[-1] if detail else "the call failed"
        raise DeliveryError(f"{path} could not be read; no deduplication may be claimed: {tail}")
    return str(getattr(result, "stdout", "") or "")


def open_issue_keys(repo: str, *, run: Callable[..., Any] = subprocess.run) -> frozenset[str]:
    """The 100Ways issue keys this repository has already been asked for, open only."""
    text = _gh_read(
        repo,
        "issues?state=open&per_page=100",
        "--jq",
        ".[] | select(.pull_request == null) | .body",
        run=run,
    )
    return frozenset(MARKER.findall(text))


def open_discussion_keys(
    repo: str, *, run: Callable[..., Any] = subprocess.run
) -> frozenset[str]:
    """The 100Ways discussion keys already on the board, open only."""
    text = _gh_read(repo, "discussions?per_page=100", "--jq", ".discussions[].body", run=run)
    return frozenset(MARKER.findall(text))


def deduplicate(result: Plan, keys: Iterable[str]) -> tuple[Plan, tuple[str, ...]]:
    """Drop what this repository has already been asked for, and name what was dropped.

    The caller supplies the keys rather than letting this module decide how to read them:
    a dry run then needs no token, and a live run says out loud which read it used.
    """
    seen = set(keys)
    dropped = tuple(
        sorted(
            [draft.key for draft in result.issues if draft.key in seen]
            + [draft.key for draft in result.discussions if draft.key in seen]
        )
    )
    return (
        Plan(
            issues=tuple(d for d in result.issues if d.key not in seen),
            discussions=tuple(d for d in result.discussions if d.key not in seen),
            suggestions=result.suggestions,
            measured=result.measured,
            skipped=result.skipped,
        ),
        dropped,
    )


def create_discussions(
    repo: str,
    drafts: Sequence[DiscussionDraft],
    apply: bool = False,
    *,
    run: Callable[..., Any] = subprocess.run,
) -> list[dict[str, object]]:
    """Create each discussion only when told to; the default reports the plan.

    Uses the REST discussions endpoint through ``gh``, with the body sent as a JSON
    document on stdin -- never interpolated into a shell command, so a finding containing
    a backquote or a newline cannot change what is executed.  A failure comes back as a
    record rather than an exception, because a partial delivery is something an operator
    has to see.
    """
    if not apply:
        return [
            {
                "key": draft.key,
                "title": draft.title,
                "category": draft.category or "(repo default)",
                "action": "skipped",
            }
            for draft in drafts
        ]
    if shutil.which("gh") is None:
        return [
            {"key": draft.key, "title": draft.title, "error": "gh CLI not on PATH"}
            for draft in drafts
        ]
    out: list[dict[str, object]] = []
    for draft in drafts:
        payload = {"title": draft.title, "body": draft.body}
        if draft.category:
            payload["category"] = draft.category
        result = run(
            ["gh", "api", f"repos/{repo}/discussions", "-X", "POST", "--input", "-"],
            input=json.dumps(payload),
            capture_output=True,
            text=True,
        )
        if getattr(result, "returncode", 1) == 0:
            out.append({"key": draft.key, "title": draft.title, "url": _url_of(result)})
            continue
        detail = (getattr(result, "stderr", "") or getattr(result, "stdout", "")).strip()
        out.append({"key": draft.key, "title": draft.title, "error": redact(detail)})
    return out


def _url_of(result: Any) -> str:
    """The html_url the API returned, or what is known when it did not return one."""
    try:
        return str(json.loads(result.stdout).get("html_url", "")) or "created; no url returned"
    except (TypeError, ValueError):
        return "created; the response was not JSON"


def deliver(
    repo: str,
    result: Plan,
    apply: bool = False,
    *,
    kinds: Sequence[str] = ("issues", "discussions"),
    run: Callable[..., Any] = subprocess.run,
) -> dict[str, object]:
    """Write the plan through the engine's one issue path plus the discussion endpoint.

    Off by default and unambiguous when on: each family reports its own records, so a
    run that created three issues and failed on one discussion says so instead of
    raising after the third create and hiding the first two.  ``kinds`` scopes the write
    -- asking for issues must not open discussions as a side effect.
    """
    unknown = [name for name in kinds if name not in ("issues", "discussions")]
    if unknown:
        raise DeliveryError(f"no family to deliver called {', '.join(unknown)}")
    issues = (
        create_issues(repo, list(result.issues), apply=apply) if "issues" in kinds else []
    )
    discussions = (
        create_discussions(repo, result.discussions, apply=apply, run=run)
        if "discussions" in kinds
        else []
    )
    return {
        "repo": repo,
        "apply": apply,
        "kinds": list(kinds),
        "planned": (len(result.issues) if "issues" in kinds else 0)
        + (len(result.discussions) if "discussions" in kinds else 0),
        "issues": issues,
        "discussions": discussions,
        "errors": [item for item in (*issues, *discussions) if "error" in item],
    }
