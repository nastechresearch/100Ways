"""Delivery: engine measurements turned into issues, discussions, and next actions.

:mod:`hundredways.red_classifier`, :mod:`hundredways.urlcheck`,
:mod:`hundredways.adapters`, :mod:`hundredways.pubconfig` and
:mod:`hundredways.errorfeed` each answer a question about a real artifact.  None of
them puts the answer where a person will see it, and a finding nobody reads is a
finding that does not exist.  This module is that last step, with one rule above all
others:

**An issue is a defect with a named owner.  A discussion is a question with no known
answer.**  Lanes classified by the red classifier, links that point nowhere, and
credential names a live job will read as an empty string each have exactly one next
action, so they are drafted as issues.  Whether a new upstream CLI verb should be
adopted or refused, and whether a file with no upstream twin is supposed to exist, are
decisions the engine is not allowed to make for a human, so they are drafted as
discussions.

Drafts are pure data until someone says otherwise.  :func:`create_issues` is imported
from :mod:`hundredways.brandaudit` rather than re-implemented: there is one GitHub
issue write path in this engine and it is dry-run by default.  Every body carries a
marker line, so a later cycle can tell what it already asked for even when the count in
the title has moved -- and reading that list is a hard error when it fails, because an
unread list is indistinguishable from an empty one.
"""

