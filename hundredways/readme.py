"""README generation: a machine-maintained project README.

The README is regenerated by CI (``stage-readme.yml``) from the ways
registry, the achievement catalog, the owned-assets registry and the CLI +
Telegram command inventories - so the counts (the way total, the trophy total)
never drift from the code that owns them.
Deterministic: given the same inputs it emits the same bytes.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass

from .achievements import ACHIEVEMENTS, Achievements
from .ways import WAYS


@dataclass(frozen=True)
class ReadmeInputs:
    ways: list = None          # Way list
    achievements: dict = None  # name -> Achievement
    state_dir: str = ""        # where achievements.json lives (empty = none unlocked)
    owned_count: int = 0       # owned-assets registry entry count
    surface: tuple = None      # SurfaceItems, or None to read them from the registries


def _plural(n: int, singular: str, plural: str | None = None) -> str:
    return singular if n == 1 else (plural or singular + "s")


@dataclass(frozen=True)
class SurfaceItem:
    """One command the engine answers to, and the words it documents itself with."""

    kind: str  # verb | command
    name: str
    description: str
    detail: str = ""

    @property
    def handle(self) -> str:
        return f"/{self.name}" if self.kind == "command" else self.name

    @property
    def line(self) -> str:
        """The exact line that counts as this item being documented."""
        tail = f" _({self.detail})_" if self.detail else ""
        return f"- `{self.handle}` — {self.description}{tail}"


class ReadmeError(RuntimeError):
    """The shipped surface could not be read, so no coverage figure may be given."""


def _count_kind(items: tuple[SurfaceItem, ...], kind: str) -> int:
    return sum(1 for item in items if item.kind == kind)


def surface() -> tuple[SurfaceItem, ...]:
    """Every CLI verb and Telegram command, read from the registries that own them.

    There is no second list of verbs maintained here on purpose: the parser and
    :data:`hundredways.telegram_commands.COMMANDS` are the surface, and a documentation
    figure computed against a hand-written copy of them would measure the copy.  The
    argparse sub-actions are the only view of the verb list the standard library offers,
    so a parser that stops exposing them is an error rather than a shorter inventory.
    """
    from .cli import build_parser
    from .telegram_commands import COMMANDS

    choices = next(
        (a for a in build_parser()._actions if getattr(a, "_choices_actions", None)), None
    )
    if choices is None:
        raise ReadmeError("the CLI parser exposes no subcommands, so verbs cannot be listed")
    items = [
        SurfaceItem("verb", action.dest, (action.help or "").strip())
        for action in choices._choices_actions
    ]
    items += [
        SurfaceItem("command", command.name, command.summary.strip(), command.level)
        for command in COMMANDS
    ]
    return tuple(items)


@dataclass(frozen=True)
class Coverage:
    """What the README actually documents, as measured against the live surface."""

    documented: int
    total: int
    missing: tuple[str, ...] = ()

    @property
    def ratio(self) -> float:
        return self.documented / self.total if self.total else 0.0

    def to_dict(self) -> dict[str, object]:
        return {
            "documented": self.documented,
            "total": self.total,
            "ratio": round(self.ratio, 4),
            "missing": list(self.missing),
        }


def measure_coverage(text: str, items: tuple[SurfaceItem, ...] | None = None) -> Coverage:
    """Count surface items whose own documentation line appears in ``text``.

    An item with a blank help string is not documentation and is never counted, so the
    figure cannot be satisfied by a bare name.  The denominator is the live inventory:
    a verb added without a doc line moves this number down, which is the point.
    """
    items = items if items is not None else surface()
    lines = {line.strip() for line in text.splitlines()}
    documented = 0
    missing: list[str] = []
    for item in items:
        if not item.description:
            missing.append(f"{item.handle} (the code gives it no help string)")
        elif item.line not in lines:
            missing.append(f"{item.handle} (its own line is not in the README)")
        else:
            documented += 1
    return Coverage(documented, len(items), tuple(missing))


def render_readme(inp: ReadmeInputs) -> str:
    ways = inp.ways if inp.ways is not None else WAYS
    achievements = inp.achievements if inp.achievements is not None else ACHIEVEMENTS
    items = inp.surface if inp.surface is not None else surface()
    by_category = Counter(w.category for w in ways)
    ach = Achievements(inp.state_dir) if inp.state_dir else None
    trophies = ach.trophies() if ach else []
    lines = [
        "# 100Ways",
        "",
        "A rebrand-safe fork-sync engine that ports the upstream Hermes agent",
        "into the Nastech fork while keeping parity and the brand intact.",
        "",
        "## At a glance",
        "",
        f"- {len(ways)} ways across {len(by_category)} strategy categories",
        f"- {len(achievements)} achievements, {len(trophies)} unlocked",
        f"- {inp.owned_count} owned-asset registry entries (see config/owned-assets/)",
        f"- {len(_ordered_stages())} pipeline stages per update run",
        f"- {_count_kind(items, 'verb')} CLI verbs and "
        f"{_count_kind(items, 'command')} Telegram commands",
        "",
        "## Ways",
        "",
    ]
    for category in sorted(by_category):
        names = [w.name for w in ways if w.category == category]
        lines.append(f"### {category} ({len(names)} {_plural(len(names), 'way')})")
        lines.append("")
        for name in names:
            lines.append(f"- {name}")
        lines.append("")
    for kind, heading in (("verb", "CLI verbs"), ("command", "Telegram commands")):
        members = [item for item in items if item.kind == kind]
        lines.append(f"## {heading}")
        lines.append("")
        lines.extend(item.line for item in members)
        lines.append("")
    lines.append("## Achievements")
    lines.append("")
    for name, meta in achievements.items():
        mark = "✅" if any(t.name == meta.name for t in trophies) else "▢"
        lines.append(f"- {mark} {meta.emoji} {name} — {meta.description}")
    lines.append("")
    lines.append("## Trophies")
    lines.append("")
    if trophies:
        for t in trophies:
            lines.append(f"- {t.emoji} {t.name} — {t.description}")
    else:
        lines.append("_None unlocked yet._")
    lines.append("")
    lines.append("## Pipeline stages")
    lines.append("")
    for i, stage in enumerate(_ordered_stages(), 1):
        lines.append(f"{i}. {stage}")
    lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("Generated by `100ways readme`; do not edit by hand.")
    lines.append("")
    return "\n".join(lines)


def _ordered_stages():
    # imported lazily so `readme` never drags the git plumbing in
    from .updates import STAGES
    return STAGES


def render_readme_for_repo(repo: str, state_dir: str = "", owned_count: int = 0) -> str:
    """Convenience: build ReadmeInputs from a repo checkout and render."""
    return render_readme(ReadmeInputs(state_dir=state_dir, owned_count=owned_count))
